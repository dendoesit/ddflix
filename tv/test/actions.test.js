const a = require('assert'), { actionsFor } = require('../js/actions.js');
const movie = { type: 'movie', trailer: 'yt' };
let r = actionsFor(movie, { next: { id: 1, position: 0 } }, {});
a.strictEqual(r.primary.key, 'title.play'); a.deepStrictEqual(r.icons.map(i => i.id), ['mylist', 'rate']); a.ok(r.tabs.includes('audiosubs')); a.ok(r.tabs.includes('trailers'));
r = actionsFor({ type: 'series', seasons: [{}] }, { next: { id: 2, season: 3, episode: 4, position: 600 } }, { inList: true });
a.strictEqual(r.primary.key, 'title.resumeSE'); a.deepStrictEqual(r.primary.vars, { s: 3, e: 4 });
a.deepStrictEqual(r.icons.map(i => i.id), ['mylist', 'restart', 'rate', 'remove']); a.strictEqual(r.icons[0].on, true); a.strictEqual(r.tabs[0], 'episodes');
r = actionsFor(movie, {}, {});
a.strictEqual(r.primary, null); a.strictEqual(r.note.key, 'title.nodl'); a.deepStrictEqual(r.icons.map(i => i.id), ['mylist']);
a.deepStrictEqual(r.tabs, ['details', 'similar', 'trailers']);
r = actionsFor({ type: 'movie', downloads: [{ state: 'downloading', progress: 42 }] }, {}, {});
a.strictEqual(r.primary.id, 'dlprog'); a.strictEqual(r.primary.vars.p, 42);
r = actionsFor({ type: 'movie', downloading: true, progress: 7.4 }, null, {}); a.strictEqual(r.primary.vars.p, 7);
const V = (res, s, rank) => ({ id: res + s, resolution: res, seeders: s, rank: rank || 1 });
const pr = require('../js/actions.js').pickRelease;
a.strictEqual(pr({ versions: [V('2160p', 50), V('1080p', 6), V('720p', 99)] }).id, '1080p6');
a.strictEqual(pr({ versions: [V('2160p', 50), V('1080p', 2), V('720p', 99)] }).id, '2160p50');
a.strictEqual(pr({ versions: [V('2160p', 1), V('1080p', 2), V('720p', 3)] }).id, '720p3');
a.strictEqual(pr({ versions: [V('1080p', 0)] }), null);
r = actionsFor({ type: 'movie', versions: [V('1080p', 9)] }, {}, {}); a.strictEqual(r.primary.id, 'download');
